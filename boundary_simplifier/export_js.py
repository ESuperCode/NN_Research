"""
export_js.py

Exports a fitted SimplifiedBoundaryModel to a single, dependency-free
JavaScript file that runs entirely client-side in a browser -- no server,
no Python, no ML library. This is the direct payoff of folding the whole
surrogate into a handful of NumPy arrays: those arrays (and the small
amount of math that combines them) translate one-for-one into vanilla JS.

What gets exported, per basis:
  - "poly2": mean, P (PCA projection), a, W, c  -> score = c + z.a + z^T W z
  - "polyN": mean, P, idx, coef, c              -> score = c + sum coef_m * monomial_m(z)
  - "rbf":   mean, P, Omega, b, w, c, scale      -> score = c + sum w_i cos(omega_i.z + b_i)

Optionally also exports a scikit-learn TfidfVectorizer's vocabulary + IDF
weights, so raw text can be vectorized client-side too (see
`export_tfidf_vectorizer`) -- the JS tokenizer matches sklearn's default
token pattern (`\\b\\w\\w+\\b`, lowercased) and default L2 normalization,
so vectors match sklearn's own `.transform()` output on the same text
(verified numerically against Node.js in this project's test run).

Usage:
    from export_js import export_model_to_js
    export_model_to_js(simplified_model, "classifier.js", vectorizer=vec)
"""

import json
import numpy as np


def _arr(a):
    """NumPy array -> nested Python list, JSON-safe."""
    return None if a is None else np.asarray(a).tolist()


def _model_to_params_dict(model):
    d = {"basis": model.basis, "n_components": model.n_components,
         "mean": _arr(model.mean), "P": _arr(model.P)}
    p = model.params
    if model.basis == "poly2":
        d["a"] = _arr(p["a"]); d["W"] = _arr(p["W"]); d["c"] = p["c"]
    elif model.basis == "polyN":
        d["idx"] = _arr(p["idx"]); d["coef"] = _arr(p["coef"]); d["c"] = p["c"]
    elif model.basis == "rbf":
        d["Omega"] = _arr(p["Omega"]); d["b"] = _arr(p["b"])
        d["w"] = _arr(p["w"]); d["c"] = p["c"]; d["scale"] = p["scale"]
    return d


def _vectorizer_to_params_dict(vectorizer):
    """Extracts what's needed to reproduce TfidfVectorizer(stop_words='english')
    .transform() in JS: vocabulary (word -> column index), per-feature IDF
    weights, and whether L2 normalization is applied (sklearn default)."""
    return {
        "vocabulary": {word: int(idx) for word, idx in vectorizer.vocabulary_.items()},
        "idf": vectorizer.idf_.tolist(),
        "lowercase": bool(vectorizer.lowercase),
        "norm": vectorizer.norm or None,
    }


_JS_TEMPLATE = r"""// Auto-generated by export_js.py -- a self-contained, dependency-free
// JavaScript port of a Python closed-form decision-boundary surrogate.
// No build step, no imports: load this file with a standard script tag
// and use the global BoundaryClassifier class it defines below.
// (Note for anyone editing this template: never put the closing script
// tag's character sequence inside this file as literal text, even inside
// a JS comment or string -- the HTML parser ends the enclosing script
// element the instant it sees that sequence, comment or not, which
// silently truncates the real code that follows it.)

const MODEL_PARAMS = __MODEL_JSON__;
const VECTORIZER_PARAMS = __VECTORIZER_JSON__;  // null if not exported

function _sigmoid(x) { return 1 / (1 + Math.exp(-x)); }

function _matVec(M, v) {
  // M: (rows x cols) nested array, v: (cols) array -> (rows) array
  const out = new Array(M.length);
  for (let i = 0; i < M.length; i++) {
    let s = 0;
    const row = M[i];
    for (let j = 0; j < row.length; j++) s += row[j] * v[j];
    out[i] = s;
  }
  return out;
}

class BoundaryClassifier {
  constructor(params) { this.p = params; }

  // x: plain array of raw feature values (already vectorized, same
  // dimensionality the Python model was trained on).
  _project(x) {
    if (!this.p.P) return x;  // skip_pca case: input IS the reduced space
    const d = this.p.P.length, k = this.p.P[0].length;
    const centered = new Array(d);
    for (let i = 0; i < d; i++) centered[i] = x[i] - this.p.mean[i];
    const z = new Array(k).fill(0);
    for (let i = 0; i < d; i++) {
      const row = this.p.P[i];
      const ci = centered[i];
      if (ci === 0) continue;
      for (let j = 0; j < k; j++) z[j] += ci * row[j];
    }
    return z;
  }

  _score(z) {
    const p = this.p;
    if (p.basis === "poly2") {
      let quad = 0;
      const Wz = _matVec(p.W, z);
      for (let i = 0; i < z.length; i++) quad += z[i] * Wz[i];
      let lin = 0;
      for (let i = 0; i < z.length; i++) lin += z[i] * p.a[i];
      return p.c + lin + quad;
    } else if (p.basis === "polyN") {
      let score = p.c;
      for (let f = 0; f < p.idx.length; f++) {
        let term = 1;
        for (const col of p.idx[f]) { if (col >= 0) term *= z[col]; }
        score += term * p.coef[f];
      }
      return score;
    } else if (p.basis === "rbf") {
      const D = p.b.length;
      let score = p.c;
      for (let j = 0; j < D; j++) {
        let dot = p.b[j];
        for (let i = 0; i < z.length; i++) dot += z[i] * p.Omega[i][j];
        score += Math.cos(dot) * p.scale * p.w[j];
      }
      return score;
    }
    throw new Error("Unknown basis: " + p.basis);
  }

  // x: array of raw feature values -> P(class=1) in [0,1]
  predictProba(x) {
    return _sigmoid(this._score(this._project(x)));
  }

  // x: array of raw feature values -> 0 or 1
  predict(x) {
    return this.predictProba(x) >= 0.5 ? 1 : 0;
  }
}

// --- Optional: client-side TF-IDF vectorizer matching sklearn's default
// TfidfVectorizer(stop_words='english').transform() on the SAME vocabulary
// this model was trained with. Only present if a vectorizer was exported.
class TfidfVectorizerJS {
  constructor(params) {
    this.vocab = params.vocabulary;
    this.idf = params.idf;
    this.lowercase = params.lowercase;
    this.norm = params.norm;
    this.dim = params.idf.length;
  }

  _tokenize(text) {
    if (this.lowercase) text = text.toLowerCase();
    // Matches sklearn's default token_pattern: r"(?u)\b\w\w+\b"
    return text.match(/[a-zA-Z0-9_]{2,}/g) || [];
  }

  transform(text) {
    const counts = new Array(this.dim).fill(0);
    for (const tok of this._tokenize(text)) {
      const idx = this.vocab[tok];
      if (idx !== undefined) counts[idx] += 1;
    }
    const tfidf = new Array(this.dim);
    for (let i = 0; i < this.dim; i++) tfidf[i] = counts[i] * this.idf[i];
    if (this.norm === "l2") {
      let normSq = 0;
      for (let i = 0; i < this.dim; i++) normSq += tfidf[i] * tfidf[i];
      const n = Math.sqrt(normSq) || 1;
      for (let i = 0; i < this.dim; i++) tfidf[i] /= n;
    }
    return tfidf;
  }
}

const classifier = new BoundaryClassifier(MODEL_PARAMS);
const vectorizer = VECTORIZER_PARAMS ? new TfidfVectorizerJS(VECTORIZER_PARAMS) : null;

// Convenience one-shot function for text: raw string in, probability out.
function classifyText(text) {
  if (!vectorizer) throw new Error("No vectorizer was exported with this model.");
  return classifier.predictProba(vectorizer.transform(text));
}

if (typeof module !== "undefined" && module.exports) {
  module.exports = { BoundaryClassifier, TfidfVectorizerJS, classifier, vectorizer, classifyText };
}
"""


