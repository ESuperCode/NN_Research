def export_demo_html(model, vectorizer, path, title, class0_label, class1_label,
                      placeholder="Type or paste text here...", model_desc=None):
    """Builds a single self-contained HTML demo page: a text box, a
    Classify button, and the exported classifier + vectorizer inlined
    directly in a <script> tag -- no external .js file, no network
    request, works by just double-clicking the file open in a browser."""
    params = _model_to_params_dict(model)
    vec_params = _vectorizer_to_params_dict(vectorizer)
    js_body = (_JS_TEMPLATE
               .replace("__MODEL_JSON__", json.dumps(params))
               .replace("__VECTORIZER_JSON__", json.dumps(vec_params)))

    desc = model_desc or (f"{model.basis} surrogate, {model.n_components} components, "
                           f"distilled from a trained neural network")
    html = (_DEMO_HTML_TEMPLATE
            .replace("__TITLE__", title)
            .replace("__PLACEHOLDER__", placeholder)
            .replace("__CLASS0_LABEL__", class0_label)
            .replace("__CLASS1_LABEL__", class1_label)
            .replace("__MODEL_DESC__", desc)
            .replace("__JS_BODY__", js_body))
    size_kb = len(html) / 1024
    html = html.replace("__FILE_SIZE__", f"{size_kb:.0f}")

    with open(path, "w") as f:
        f.write(html)
    print(f"Wrote {path} ({size_kb:.1f} KB, fully self-contained)")
    return path


def export_model_to_js(model, path, vectorizer=None):
    params = _model_to_params_dict(model)
    vec_params = _vectorizer_to_params_dict(vectorizer) if vectorizer is not None else None

    js = (_JS_TEMPLATE
          .replace("__MODEL_JSON__", json.dumps(params))
          .replace("__VECTORIZER_JSON__", json.dumps(vec_params) if vec_params else "null"))

    with open(path, "w") as f:
        f.write(js)
    size_kb = len(js) / 1024
    print(f"Wrote {path} ({size_kb:.1f} KB, basis={model.basis}, "
          f"vectorizer={'included' if vectorizer else 'not included'})")
    return path


